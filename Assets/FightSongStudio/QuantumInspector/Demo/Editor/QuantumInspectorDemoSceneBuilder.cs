        [Serializable] public sealed class DemoValidationReport
        {
            public string unityVersion, renderPipeline, scenePath, hierarchyFingerprint;
            public int gameObjects, components, maximumDepth, wideParents, multiComponentObjects, crossObjectReferences, missingScripts, missingReferences, nullDemoReferences, activeLights, materials, prefabs, stressSubtreeObjects, nestedPrefabInstances;
            public string[] subsystems, denseGroups, showcaseObjects, externalAssetDependencies;
            public bool hierarchyRequirementsMet, sceneSaved;
        }
        public static DemoValidationReport ValidateSaved()
        {
            if (EditorApplication.isPlayingOrWillChangePlaymode) throw new InvalidOperationException("Validate the saved scene in Edit Mode.");
            var existing=SceneManager.GetSceneByPath(ScenePath);bool temporary=!existing.IsValid()||!existing.isLoaded;
            if (!temporary && existing.isDirty) throw new InvalidOperationException("Save or close the modified Demo scene before validating its saved contents.");
            var scene=temporary?EditorSceneManager.OpenScene(ScenePath,OpenSceneMode.Additive):existing;
            try{var report=Inspect(scene);RequireValid(report);WriteReport(report);return report;}
            finally{if(temporary)EditorSceneManager.CloseScene(scene,true);}
        }
        private static DemoValidationReport Inspect(Scene scene)
        {
            var roots=scene.GetRootGameObjects();var all=roots.SelectMany(go=>go.GetComponentsInChildren<Transform>(true)).ToArray();
            var dense=new List<string>();int maxDepth=0,wide=0,multi=0,count=0,missing=0,dangling=0,references=0,nullDemo=0;
            foreach(var transform in all)
            {
                int depth=0;for(var p=transform.parent;p!=null;p=p.parent)depth++;maxDepth=Math.Max(maxDepth,depth);
                if(transform.childCount>=5)wide++;
                int descendants=transform.GetComponentsInChildren<Transform>(true).Length-1;
                if(descendants>=25&&descendants<=50)dense.Add(transform.name+" ("+descendants+")");
                var components=transform.GetComponents<Component>();count+=components.Count(c=>c!=null);
                if(components.Count(c=>c!=null&&!(c is Transform))>=2)multi++;
                missing+=GameObjectUtility.GetMonoBehavioursWithMissingScriptCount(transform.gameObject);
                foreach(var component in components)
                {
                    if(component==null)continue;bool demo=component is MonoBehaviour&&component.GetType().Namespace=="FightSongStudio.QuantumInspector.Demo";
                    using(var serialized=new SerializedObject(component))
                    {
                        var property=serialized.GetIterator();while(property.Next(true))
                        {
                            if(property.propertyType!=SerializedPropertyType.ObjectReference||property.propertyPath=="m_Script")continue;
                            if(property.objectReferenceValue==null)
                            {if(property.objectReferenceInstanceIDValue!=0)dangling++;if(demo&&!property.propertyPath.StartsWith("m_",StringComparison.Ordinal))nullDemo++;continue;}
                            var target=property.objectReferenceValue as GameObject??(property.objectReferenceValue as Component)?.gameObject;
                            if(demo&&target!=null&&target.scene==scene&&target!=transform.gameObject)references++;
                        }
                    }
                }
            }
            var root=roots.Single(go=>go.name=="QuantumInspector_LivingLaboratory");
            var report=new DemoValidationReport {
                unityVersion=Application.unityVersion,renderPipeline="Universal Render Pipeline "+UnityEditor.PackageManager.PackageInfo.FindForAssembly(typeof(UniversalRenderPipelineAsset).Assembly).version,scenePath=ScenePath,
                gameObjects=all.Length,components=count,maximumDepth=maxDepth,wideParents=wide,multiComponentObjects=multi,crossObjectReferences=references,
                missingScripts=missing,missingReferences=dangling,nullDemoReferences=nullDemo,
                activeLights=all.SelectMany(t=>t.GetComponents<Light>()).Count(l=>l.enabled&&l.gameObject.activeInHierarchy),
                materials=AssetDatabase.FindAssets("t:Material",new[]{Root+"/Materials"}).Length,prefabs=AssetDatabase.FindAssets("t:Prefab",new[]{Root+"/Prefabs"}).Length,
                subsystems=root.transform.Cast<Transform>().Select(t=>t.name).ToArray(),denseGroups=dense.ToArray(),
                showcaseObjects=all.Where(t=>t.name.StartsWith("SHOWCASE_",StringComparison.Ordinal)).Select(t=>t.name).ToArray(),
                stressSubtreeObjects=root.transform.Find("06_DemoDocumentation/StressTestCluster").GetComponentsInChildren<Transform>(true).Length,
                nestedPrefabInstances=all.Count(t=>PrefabUtility.IsAnyPrefabInstanceRoot(t.gameObject)&&PrefabUtility.GetOutermostPrefabInstanceRoot(t.gameObject)!=t.gameObject),
                hierarchyFingerprint=Fingerprint(all),
                sceneSaved=!scene.isDirty&&File.Exists(ScenePath),
                externalAssetDependencies=File.Exists(ScenePath)?AssetDatabase.GetDependencies(ScenePath,true).Where(p=>p.StartsWith("Assets/",StringComparison.Ordinal)&&!p.StartsWith(Root+"/",StringComparison.Ordinal)).ToArray():Array.Empty<string>()
            };
            report.hierarchyRequirementsMet=all.Length>=250&&all.Length<=400&&maxDepth>=4&&maxDepth<=8&&wide>=20&&multi>=30&&dense.Count>=5&&report.stressSubtreeObjects>=58&&report.stressSubtreeObjects<=64&&SubsystemNames.All(n=>report.subsystems.Contains(n))&&report.showcaseObjects.Length==8&&report.nestedPrefabInstances>=2;
            return report;
        }
        private static string HierarchyPath(Transform transform)
        {
            var names=new Stack<string>();for(var t=transform;t!=null;t=t.parent)names.Push(t.name);return string.Join("/",names);
        }
        private static string Fingerprint(Transform[] transforms)
        {
            var text=new StringBuilder();
            foreach(var t in transforms.OrderBy(HierarchyPath,StringComparer.Ordinal))
            {
                text.Append(HierarchyPath(t)).Append('|').Append(t.gameObject.activeSelf);
                foreach(float value in new[]{t.localPosition.x,t.localPosition.y,t.localPosition.z,t.localRotation.x,t.localRotation.y,t.localRotation.z,t.localRotation.w,t.localScale.x,t.localScale.y,t.localScale.z})
                    text.Append('|').Append(value.ToString("R",CultureInfo.InvariantCulture));
                foreach(var component in t.GetComponents<Component>())
                {
                    if (component == null) { text.Append("|MissingScript"); continue; }
                    text.Append('|').Append(component.GetType().FullName);
                    if(!(component is MonoBehaviour)||component.GetType().Namespace!="FightSongStudio.QuantumInspector.Demo")continue;
                    using(var serialized=new SerializedObject(component))
                    {
                        var property=serialized.GetIterator();while(property.Next(true))
                        {
                            if(property.propertyType!=SerializedPropertyType.ObjectReference||property.propertyPath.StartsWith("m_",StringComparison.Ordinal))continue;
                            var target=property.objectReferenceValue as GameObject??(property.objectReferenceValue as Component)?.gameObject;
                            text.Append('|').Append(property.propertyPath).Append('=').Append(target!=null?HierarchyPath(target.transform):AssetDatabase.GetAssetPath(property.objectReferenceValue));
                        }
                    }
                }
                text.Append('\n');
            }
            using(var hash=SHA256.Create())return BitConverter.ToString(hash.ComputeHash(Encoding.UTF8.GetBytes(text.ToString()))).Replace("-","").ToLowerInvariant();
        }
        private static void RequireValid(DemoValidationReport report)
        {
            if(!report.hierarchyRequirementsMet||report.missingScripts!=0||report.missingReferences!=0||report.nullDemoReferences!=0||report.externalAssetDependencies.Length!=0)
                throw new InvalidOperationException("Demo validation failed:\n"+JsonUtility.ToJson(report,true));
        }
        private static void WriteReport(DemoValidationReport report)
        {
            string path=Root+"/Documentation/ValidationReport.json";File.WriteAllText(path,JsonUtility.ToJson(report,true)+"\n");AssetDatabase.ImportAsset(path);
        }
