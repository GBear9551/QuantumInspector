            }
            private Mesh MakeTorus()
            {
                const int segments=80,sides=10;var vertices=new Vector3[(segments+1)*(sides+1)];var normals=new Vector3[vertices.Length];var uv=new Vector2[vertices.Length];var indices=new int[segments*sides*6];
                for(int i=0;i<=segments;i++)for(int j=0;j<=sides;j++)
                {
                    float a=i*Mathf.PI*2/segments,b=j*Mathf.PI*2/sides;int index=i*(sides+1)+j;
                    Vector3 outward=new Vector3(Mathf.Cos(a),0,Mathf.Sin(a));Vector3 normal=outward*Mathf.Cos(b)+Vector3.up*Mathf.Sin(b);
                    vertices[index]=outward+normal*.027f;normals[index]=normal;uv[index]=new Vector2((float)i/segments,(float)j/sides);
                    if(i==segments||j==sides)continue;int k=(i*sides+j)*6,n=index+sides+1;
                    indices[k]=index;indices[k+1]=index+1;indices[k+2]=n;indices[k+3]=index+1;indices[k+4]=n+1;indices[k+5]=n;
                }
                string path=Root+"/Meshes/ContainmentRing.asset";var mesh=AssetDatabase.LoadAssetAtPath<Mesh>(path);
                if(mesh==null){mesh=new Mesh();AssetDatabase.CreateAsset(mesh,path);}mesh.Clear();mesh.name="ContainmentRing";mesh.vertices=vertices;mesh.normals=normals;mesh.uv=uv;mesh.triangles=indices;mesh.RecalculateBounds();EditorUtility.SetDirty(mesh);return mesh;
            }
