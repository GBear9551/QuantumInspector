            private Transform Group(string name, Transform parent, Vector3 position = default)
            {
                var go = new GameObject(name);
                SceneManager.MoveGameObjectToScene(go, scene);
                go.transform.SetParent(parent, false); go.transform.localPosition = position;
                return go.transform;
            }
            private Transform Shape(string name, Transform parent, PrimitiveType type, Vector3 position, Vector3 scale, string material, bool collider = false)
            {
                var go = GameObject.CreatePrimitive(type); go.name = name;
                SceneManager.MoveGameObjectToScene(go, scene);
                go.transform.SetParent(parent, false); go.transform.localPosition = position; go.transform.localScale = scale;
                go.GetComponent<Renderer>().sharedMaterial = materials[material];
                if (!collider) Object.DestroyImmediate(go.GetComponent<Collider>());
                return go.transform;
            }
            private Transform Box(string name, Transform parent, Vector3 position, Vector3 scale, string material, bool collider = false)
                => Shape(name, parent, PrimitiveType.Cube, position, scale, material, collider);
            private Transform Ring(string name, Transform parent, Vector3 position, float radius, string material)
            {
                var t = Group(name, parent, position); t.localScale = Vector3.one * radius;
                t.gameObject.AddComponent<MeshFilter>().sharedMesh = torus;
                t.gameObject.AddComponent<MeshRenderer>().sharedMaterial = materials[material];
                return t;
            }
            private DemoDevice Device(Transform target, Transform connection, float watts = 2)
            {
                var device = target.gameObject.AddComponent<DemoDevice>(); device.Configure(target.name, connection, watts); devices.Add(device); return device;
            }
            private DemoSensor Sensor(Transform target, Transform observed, float phase)
            {
                var sensor = target.gameObject.AddComponent<DemoSensor>(); sensor.Configure(observed, reactor, phase); sensors.Add(sensor); return sensor;
            }
            private void Spin(Transform target, Vector3 velocity) => rotors.Add(new DemoLabAnimator.Rotor { target = target, degreesPerSecond = velocity });
            private void Pulse(Transform target, Color color, float phase = 0, bool blink = false)
                => pulses.Add(new DemoLabAnimator.Pulse { target = target.GetComponent<Renderer>(), color = color, phase = phase, blink = blink });
            private Transform Label(string name, string text, Transform parent, Vector3 position, float size, Color color)
            {
                var t = Group(name, parent, position);
                var label = t.gameObject.AddComponent<TextMesh>();
                label.text = text; label.font = Resources.GetBuiltinResource<Font>("LegacyRuntime.ttf");
                label.fontSize = 64; label.characterSize = size; label.anchor = TextAnchor.MiddleCenter; label.alignment = TextAlignment.Center; label.color = color;
                t.GetComponent<MeshRenderer>().sharedMaterial = label.font.material;
                return t;
            }
            private void PointLight(string name, Transform parent, Vector3 position, Color color, float intensity, float range)
            {
                var light = Group(name, parent, position).gameObject.AddComponent<Light>();
                light.gameObject.AddComponent<UniversalAdditionalLightData>();
                light.type = LightType.Point; light.color = color; light.intensity = intensity; light.range = range; light.shadows = LightShadows.None;
            }

