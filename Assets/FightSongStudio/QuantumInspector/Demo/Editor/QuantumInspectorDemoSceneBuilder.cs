        public static DemoValidationReport Build()
        {
            if (EditorApplication.isPlayingOrWillChangePlaymode) throw new InvalidOperationException("Generate in Edit Mode.");
            if (!(GraphicsSettings.currentRenderPipeline is UniversalRenderPipelineAsset))
                throw new InvalidOperationException("This demo targets the existing Universal Render Pipeline. No pipeline settings were changed.");
            if (File.Exists(ScenePath) && (!File.Exists(StampPath) || File.ReadAllText(StampPath).Trim() != Stamp))
                throw new InvalidOperationException("Refusing to overwrite a scene not identified as generated by this builder.");
            for (int i = 0; i < SceneManager.sceneCount; i++)
            {
                var open = SceneManager.GetSceneAt(i);
                if (open.path == ScenePath && open.isDirty)
                    throw new InvalidOperationException("Save or close the modified Demo scene before regenerating it.");
            }
            foreach (string folder in new[] { "Scenes", "Materials", "Meshes", "Prefabs", "Settings", "Documentation" })
                Directory.CreateDirectory(Root + "/" + folder);
            AssetDatabase.Refresh();
            if (File.Exists(ScenePath))
            {
                Directory.CreateDirectory(Root + "/Editor/Backups~");
                File.Copy(ScenePath, Root + "/Editor/Backups~/Demo.previous.unity", true);
            }
            Scene original = SceneManager.GetActiveScene();
            var existingDemo = SceneManager.GetSceneByPath(ScenePath);
            bool reopen = existingDemo.IsValid() && existingDemo.isLoaded;
            Scene scene = EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Additive);
            SceneManager.SetActiveScene(scene);
            if (reopen) EditorSceneManager.CloseScene(existingDemo, true);
            bool saved = false;
            try
            {
                var context = new Laboratory(scene);
                context.Construct();
                var report = Inspect(scene);
                RequireValid(report);
                if (!EditorSceneManager.SaveScene(scene, ScenePath)) throw new IOException("Could not save Demo.unity.");
                saved = true;
                report.sceneSaved = true;
                // Save only our assets: SaveAssets would also flush unrelated dirty project assets.
                foreach (string guid in AssetDatabase.FindAssets("", new[] { Root }))
                    AssetDatabase.SaveAssetIfDirty(new GUID(guid));
                File.WriteAllText(StampPath, Stamp + "\n");
                WriteReport(report);
                Debug.Log($"Living Laboratory generated: {report.gameObjects} GameObjects, {report.components} components, depth {report.maximumDepth}, {report.crossObjectReferences} serialized cross-object references. " + ScenePath);
                return report;
            }
            finally
            {
                if (!(reopen && saved))
                {
                    if (reopen) EditorSceneManager.OpenScene(ScenePath, OpenSceneMode.Additive);
                    EditorSceneManager.CloseScene(scene, true);
                }
                if (original.IsValid() && original.isLoaded) SceneManager.SetActiveScene(original);
                AssetDatabase.Refresh();
            }
        }

        public static void FrameScene()
        {
            var view = SceneView.lastActiveSceneView;
            if (view == null) return;
            view.LookAt(new Vector3(0, 1, 0), Quaternion.Euler(35, -35, 0), 20, false, true);
            view.sceneViewState.showImageEffects = true;
        }

