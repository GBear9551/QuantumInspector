var animator = UnityEngine.Object.FindFirstObjectByType<FightSongStudio.QuantumInspector.Demo.DemoLabAnimator>();
var state = new UnityEditor.SerializedObject(animator);
var rotor = (UnityEngine.Transform)state.FindProperty("rotors").GetArrayElementAtIndex(0).FindPropertyRelative("target").objectReferenceValue;
var arm = UnityEngine.Object.FindFirstObjectByType<FightSongStudio.QuantumInspector.Demo.DemoRoboticArm>();
var joint = (UnityEngine.Transform)new UnityEditor.SerializedObject(arm).FindProperty("joints").GetArrayElementAtIndex(1).objectReferenceValue;
bool rotorMoved = UnityEngine.Vector3.Distance(rotor.localEulerAngles, UnityEditor.SessionState.GetVector3("QI.Demo.Test.Rotor", Vector3.zero)) > .01f;
bool armMoved = UnityEngine.Vector3.Distance(joint.localEulerAngles, UnityEditor.SessionState.GetVector3("QI.Demo.Test.Joint", Vector3.zero)) > .01f;
bool advanced = animator.SimulationTime > UnityEditor.SessionState.GetFloat("QI.Demo.Test.Time",0);
if (!rotorMoved || !armMoved || !advanced) throw new System.Exception("Play Mode motion did not advance.");
animator.SetAnimationEnabled(false);
UnityEditor.SessionState.SetFloat("QI.Demo.Test.PauseTime", animator.SimulationTime);
var console = UnityEngine.Object.FindFirstObjectByType<FightSongStudio.QuantumInspector.Demo.DemoControlConsole>();
var reactor = UnityEngine.Object.FindFirstObjectByType<FightSongStudio.QuantumInspector.Demo.DemoReactorController>();
console.CyclePower(); float high = reactor.Output;
console.CyclePower(); float low = reactor.Output;
console.CyclePower(); float mid = reactor.Output;
if (high != 1 || low != .15f || mid != .65f) throw new System.Exception("Power control failed.");
animator.NextView();
return new {framesAdvanced=UnityEngine.Time.frameCount-UnityEditor.SessionState.GetInt("QI.Demo.Test.Frame",0), simulationAdvanced=advanced, rotorMoved, armMoved, pausedTime=animator.SimulationTime, powerCycle=new[]{high,low,mid}, viewIndex=animator.ViewIndex};
